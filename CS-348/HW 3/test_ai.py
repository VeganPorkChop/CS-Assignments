class CountingGame(Game):
    """A Game that counts calls to generate_all_moves(), i.e. the nodes a search expands."""

    def __init__(self):
        super().__init__()
        self.nodes = 0

    def generate_all_moves(self, board, color):
        self.nodes += 1
        return super().generate_all_moves(board, color)


def make_board(number):
    return Board() if number is None else Board(getattr(board_configs, 'board_config%d' % number))


def describe(number):
    return 'the opening position' if number is None else 'board_config%d' % number


def board_text(board):
    if not isinstance(board, Board):
        return '    %r (not a Board)' % (board,)
    return '\n'.join('    ' + str(row) for row in board.to_board_config())


class CountsTest(unittest.TestCase):
    """Part 1: counts(), checked directly on boards 1-6 and through evaluate() on boards 1-12."""

    PIECES = [[7, 13], [7, 12], [6, 12], [1, 11], [1, 10], [2, 12]]
    KINGS = [[2, 2], [2, 3], [3, 2], [1, 0], [1, 0], [1, 0]]
    MOVES = [[8, 17], [10, 14], [7, 11], [0, 12], [1, 12], [0, 12]]
    OPPORTUNITIES = [[3, 4], [4, 3], [1, 3], [0, 0], [1, 0], [0, 1]]
    KING_HOPEFULS = [[0, 0], [1, 0], [1, 0], [0, 2], [0, 2], [0, 2]]

    def test_counts(self):
        game = Game()
        names = ['num_pieces', 'num_kings', 'num_moves', 'num_opportunities', 'num_king_hopefuls']
        tables = [self.PIECES, self.KINGS, self.MOVES, self.OPPORTUNITIES, self.KING_HOPEFULS]
        for b in range(6):
            for c, (color, player) in enumerate([(PLAYER1_PIECE_COLOR, 'Player 1'), (PLAYER2_PIECE_COLOR, 'Player 2')]):
                with self.subTest(board='board_config%d' % (b + 1), player=player):
                    result = counts(make_board(b + 1), game, color)
                    self.assertIsInstance(result, tuple, 'counts() must return a tuple of five ints')
                    self.assertEqual(len(result), 5, 'counts() must return a tuple of five ints')
                    for name, table, value in zip(names, tables, result):
                        self.assertEqual(value, table[b][c], '%s for %s on board_config%d is %s, expected %s'
                                         % (name, player, b + 1, value, table[b][c]))

    def _check_evaluate(self, expected, **weights):
        game = Game()
        for b, want in enumerate(expected):
            with self.subTest(board='board_config%d' % (b + 1)):
                got = evaluate(make_board(b + 1), game, **weights)
                self.assertEqual(got, want, 'evaluate(board_config%d, %s) is %s, expected %s'
                                 % (b + 1, weights or 'default weights', got, want))

    def test_evaluate_1_default_weights(self):
        self._check_evaluate([6.0, 6.0, 5.0, 9.0, 8.0, 9.0, 8.0, 10.0, 10.0, 4.0, 3.0, 4.0])

    def test_evaluate_2_all_weights_one(self):
        self._check_evaluate([16.0, 8.0, 10.0, 23.0, 20.0, 24.0, 22.0, 25.0, 23.0, 9.0, 10.0, 13.0],
                             moves_weight=1.0, opportunities_weight=1.0, king_hopefuls_weight=1.0)

    def test_evaluate_3_mixed_weights(self):
        self._check_evaluate([11.0, 7.25, 7.75, 15.5, 13.5, 16.0, 14.5, 16.75, 16.0, 6.25, 6.25, 8.25],
                             pieces_weight=1.0, kings_weight=1.0, moves_weight=0.5, opportunities_weight=0.5,
                             king_hopefuls_weight=0.25)

    def test_evaluate_4_zero_weights(self):
        self._check_evaluate([0.0] * 12, pieces_weight=0.0, kings_weight=0.0, moves_weight=0.0,
                             opportunities_weight=0.0, king_hopefuls_weight=0.0)


class _SearchChecks(unittest.TestCase):

    def check_move(self, name, start, depth, params, expected_board, expected_score, result):
        where = '%s from %s at depth %d with eval_params=%s' % (name, describe(start), depth, params)
        self.assertIsInstance(result, tuple, '%s must return a (score, best_move) tuple' % name)
        self.assertEqual(len(result), 2, '%s must return a (score, best_move) tuple' % name)
        score, move = result
        want = make_board(expected_board)
        self.assertTrue(compare_boards(move, want),
                        '%s returned the wrong move.\n  returned:\n%s\n  expected (board_config%d):\n%s'
                        % (where, board_text(move), expected_board, board_text(want)))
        self.assertEqual(score, expected_score, '%s found the right move but scored it %s, expected %s'
                         % (where, score, expected_score))


class MinimaxTest(_SearchChecks):
    """Part 2: minimax(), with no pruning."""

    def test_minimax_visits_the_whole_tree(self):
        for start, depth, params, _, _, full_tree, _ in SEARCH_CASES:
            with self.subTest(start=describe(start), depth=depth):
                game = CountingGame()
                minimax(make_board(start), depth, True, game, params)
                self.assertEqual(game.nodes, full_tree,
                                 'minimax from %s at depth %d expanded %d boards (calls to generate_all_moves), '
                                 'expected exactly %d. More: generating moves at depth 0 or more than once per board '
                                 '(rules S1, S2). Fewer: something cuts the search short, which plain Minimax must '
                                 'not do.' % (describe(start), depth, game.nodes, full_tree))


class AlphaBetaTest(_SearchChecks):
    """Part 3: minimax_alpha_beta(). Same answers as minimax(), fewer boards expanded."""

    def test_alpha_beta_prunes(self):
        for start, depth, params, _, _, full_tree, reference in SEARCH_CASES:
            with self.subTest(start=describe(start), depth=depth):
                game = CountingGame()
                minimax_alpha_beta(make_board(start), depth, -INF, INF, True, game, params)
                if reference < full_tree:
                    self.assertLess(game.nodes, full_tree,
                                    'alpha-beta from %s at depth %d expanded %d boards, not fewer than the %d plain '
                                    'Minimax expands, so it is not pruning (the reference expands %d). Update '
                                    'alpha/beta after every move and stop as soon as beta <= alpha (rule S6). '
                                    'beta < alpha is also valid Alpha-Beta, but this assignment uses <= so ties '
                                    'prune and this test can see it (README, "Why <= and not <?").'
                                    % (describe(start), depth, game.nodes, full_tree, reference))
                else:
                    self.assertLessEqual(game.nodes, full_tree,
                                         'alpha-beta from %s at depth %d expanded %d boards, more than the %d plain '
                                         'Minimax expands' % (describe(start), depth, game.nodes, full_tree))


def _add_search_tests():
    for i, (start, depth, params, expected_board, expected_score, _, _) in enumerate(SEARCH_CASES, 1):
        def mm(self, start=start, depth=depth, params=params, b=expected_board, s=expected_score):
            result = minimax(make_board(start), depth, True, Game(), params)
            self.check_move('minimax', start, depth, params, b, s, result)

        def ab(self, start=start, depth=depth, params=params, b=expected_board, s=expected_score):
            result = minimax_alpha_beta(make_board(start), depth, -INF, INF, True, Game(), params)
            self.check_move('minimax_alpha_beta', start, depth, params, b, s, result)

        doc = 'from %s, depth %d, eval_params=%s' % (describe(start), depth, params)
        mm.__doc__ = ab.__doc__ = doc
        setattr(MinimaxTest, 'test_minimax_%02d' % i, mm)
        setattr(AlphaBetaTest, 'test_alpha_beta_%02d' % i, ab)


_add_search_tests()


